const { src, dest, watch, series } = require('gulp');
const sass = require('gulp-sass')(require('sass'));
const cleanCSS = require('gulp-clean-css');
const uglify = require('gulp-uglify');
const rename = require('gulp-rename');

// Compile SCSS entry points to an expanded .css (loaded when COOKED_DEV is on) and a .min.css.
function compile(entries, output) {
  return src(entries)
    .pipe(sass({ style: 'expanded' }).on('error', sass.logError))
    .pipe(dest(output))
    .pipe(cleanCSS())
    .pipe(rename({ suffix: '.min' }))
    .pipe(dest(output));
}

// CSS Tasks.
function css() {
  return compile(['assets/scss/style.scss', 'assets/scss/print.scss', 'assets/scss/print-only.scss'], 'assets/css');
}

function cssAdmin() {
  return compile(['assets/admin/scss/style.scss', 'assets/admin/scss/essentials.scss', 'assets/admin/scss/cooked-tom-select.scss'], 'assets/admin/css');
}

// The icon font CSS is generated by scripts/embed-icons-font.js, not SCSS.
function cssIcons() {
  return src('assets/css/icons.css')
    .pipe(cleanCSS())
    .pipe(rename({ suffix: '.min' }))
    .pipe(dest('assets/css'));
}

// JavaScript Task.
function js() {
  return src('assets/js/cooked-functions.js')
    .pipe(uglify())
    .pipe(rename({ suffix: '.min' }))
    .pipe(dest('assets/js'));
}

function jsAdmin() {
  return src(['assets/admin/js/cooked-functions.js', 'assets/admin/js/cooked-migration.js'])
    .pipe(uglify())
    .pipe(rename({ suffix: '.min' }))
    .pipe(dest('assets/admin/js'));
}

// Watch Task.
function watchFiles() {
  watch('assets/scss/**/*.scss', css);
  watch(['assets/admin/scss/**/*.scss', 'assets/scss/abstracts/*.scss'], cssAdmin);
  watch('assets/css/icons.css', cssIcons);
  watch('assets/js/cooked-functions.js', js);
  watch(['assets/admin/js/cooked-functions.js', 'assets/admin/js/cooked-migration.js'], jsAdmin);
}

// Task for building for production.
const build = series(css, cssAdmin, cssIcons, js, jsAdmin);
exports.build = build;

// Export the default Gulp task.
exports.default = series(build, watchFiles);
